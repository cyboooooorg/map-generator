def rho_ih(T, p):
    tau = T / TT; pi = p / PT; pi0 = P0 / PT
    g0p = sum(G0[k] * k / PT * (pi - pi0)**(k-1) for k in range(1, 5))
    r2p = sum(R2[k] * k / PT * (pi - pi0)**(k-1) for k in range(1, 3))
    br = (T2 - tau)*cmath.log(T2 - tau) + (T2 + tau)*cmath.log(T2 + tau) - 2*T2*cmath.log(T2) - tau*tau/T2
    gp = g0p + TT * (r2p * br).real
    return 1 / gp

