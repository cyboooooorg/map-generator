TC, RHOC, R = 647.096, 322.0, 461.51805

def phir_d(delta, tau):
    s = 0.0
    for c, d, t, n in T95:
        if c == 0:
            s += n * d * delta**(d-1) * tau**t
        else:
            s += n * math.exp(-delta**c) * delta**(d-1) * tau**t * (d - c * delta**c)
    for d, t, n, a, b, g, e in G95:
        s += n * delta**d * tau**t * math.exp(-a*(delta-e)**2 - b*(tau-g)**2) * (d/delta - 2*a*(delta-e))
    for a, b, B, n, C, D, A, beta in N95:
        dm = delta - 1.0; q = dm*dm
        theta = (1 - tau) + A * q**(1/(2*beta))
        Delta = theta**2 + B * q**a
        psi = math.exp(-C*q - D*(tau-1)**2)
        dpsi = -2*C*dm*psi
        dDelta = dm * (A*theta*2/beta*q**(1/(2*beta)-1) + 2*B*a*q**(a-1))
        dDb = b * Delta**(b-1) * dDelta
        s += n * (Delta**b * (psi + delta*dpsi) + dDb*delta*psi)
    return s

def p95(T, rho):
    d = rho / RHOC
    return rho * R * T * (1 + d * phir_d(d, TC / T))

def rho95(T, p, lo=900.0, hi=1500.0):
    r = 1000.0
    for _ in range(30):
        f = p95(T, r) - p
        h = 1e-4
        sl = (p95(T, r+h) - p95(T, r-h)) / (2*h)
        dr = f / sl
        r -= dr
        if abs(dr) < 1e-10 * r: return r
    for _ in range(200):
        m = 0.5*(lo+hi)
        if p95(T, m) < p: lo = m
        else: hi = m
    return 0.5*(lo+hi)

