// The resolution chips under a planet (components/SizeChips.svelte): one
// per size offered or on disk, and what each can do.
import { sizeName } from './api/client';
import type { BodySizes } from './api/types/BodySizes';
import type { PendingSize } from './api/types/PendingSize';

export { sizeName };

/** The width and height of a size name, `WxH` (see sizeName); null when it is not one. */
export function parseSize(name: string): [number, number] | null {
  const match = /^(\d+)x(\d+)$/.exec(name);
  if (!match) return null;
  return [Number(match[1]), Number(match[2])];
}

/**
 * A size of the body being generated by a job this tab does not follow
 * (started in another tab, or before a reload), to follow while `busy` is
 * false (no generation followed already); `followed`: the jobs this tab has
 * followed, which a listing may still name for a moment after they end.
 */
export function pendingToFollow(sizes: BodySizes, busy: boolean, followed: ReadonlySet<string>): PendingSize | null {
  if (busy) return null;
  return sizes.pending.find((p) => !followed.has(p.job_id)) ?? null;
}

/** One chip: a resolution of the body shown. */
export interface SizeChip {
  /** `WxH` (see sizeName), as the API names it. */
  size: string;
  width: number;
  height: number;
  /** On disk: a click shows it. Not on disk: a click generates it. */
  present: boolean;
  /** The one shown. */
  shown: boolean;
  /** On disk and not the original: it can be deleted. */
  deletable: boolean;
  /** Not on disk and larger than this server accepts: it cannot be generated. */
  tooLarge: boolean;
  /** Being generated, here or in another tab. */
  generating: boolean;
}

/**
 * The chips of a body's resolutions: its presets and its sizes on disk,
 * smallest first. `shown` and `generating` are `WxH` names.
 */
export function chipStates(sizes: BodySizes, shown: string, generating: string | null): SizeChip[] {
  const all = new Map<string, [number, number]>();
  for (const [w, h] of sizes.presets) all.set(sizeName(w, h), [w, h]);
  for (const p of sizes.present) all.set(sizeName(p.width, p.height), [p.width, p.height]);
  const original = sizeName(...sizes.original);
  const onDisk = new Set(sizes.present.map((p) => sizeName(p.width, p.height)));
  const pending = new Set(sizes.pending.map((p) => sizeName(p.width, p.height)));
  return [...all.entries()]
    .sort(([, a], [, b]) => a[0] * a[1] - b[0] * b[1] || a[0] - b[0])
    .map(([size, [width, height]]) => {
      const present = onDisk.has(size);
      return {
        size,
        width,
        height,
        present,
        shown: present && size === shown,
        deletable: present && size !== original,
        tooLarge: !present && (Math.max(width, height) > sizes.max_size || width * height > sizes.max_pixels),
        generating: !present && (size === generating || pending.has(size)),
      };
    });
}

/**
 * The map size a blank or reopened generation form starts with, as `WxH`.
 * `initial` is the size of the world the form opens on (Vary, drift): a real
 * size, kept as it is. `remembered` is the size of the last form submitted:
 * reused only if it is still one of the server's 2:1 presets and fits its
 * limits, so a size remembered from before the presets (1920x1080) is dropped.
 */
export function initialFormSize(
  initial: [number, number] | null,
  remembered: string | undefined,
  spec: {
    size_presets: [number, number][];
    default_width: number;
    default_height: number;
    max_size: number;
    max_pixels: number;
  },
): string {
  if (initial) return sizeName(initial[0], initial[1]);
  const parsed = remembered === undefined ? null : parseSize(remembered);
  if (parsed) {
    const [w, h] = parsed;
    const preset = spec.size_presets.some(([pw, ph]) => pw === w && ph === h);
    if (preset && w <= spec.max_size && h <= spec.max_size && w * h <= spec.max_pixels) {
      return sizeName(w, h);
    }
  }
  return sizeName(spec.default_width, spec.default_height);
}
