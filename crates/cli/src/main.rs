/// Procedural planet map generator.
///
/// Every omitted option comes from the planet archetype or is chosen
/// randomly; the planet model derives the rest. The chosen values are
/// printed so any world can be regenerated by passing them back explicitly.
///
/// Environment: MAPGEN_NO_NOISE_MAPS=true (or 1) skips the diagnostic noise
/// maps, like --no-noise-maps; MAPGEN_NO_SVG=true skips world.svg, like
/// --no-svg.
#[derive(Parser)]
#[command(version, about)]
struct Args {
    /// Planet archetype: a built-in name (earth-like, mars-like,
    /// jupiter-like, hot-jupiter… see --list-planets) or a path to a .toml
    /// archetype file. An archetype names a mass, a composition and an
    /// orbit; the planet's air, water, size and look follow from them.
    /// A moon archetype (titan-like…) is asked for with --system
    /// [default: none, the planet drawn from where it formed]
    #[arg(long)]
    planet: Option<String>,

    /// List the built-in planet and moon archetypes and exit
    #[arg(long)]
    list_planets: bool,

    /// Mass of the planet in Earth masses, in [0.01, 4131] (Mars: 0.107,
    /// Jupiter: 318) [default: the archetype's, else drawn like a small
    /// planet's]
    #[arg(long, value_parser = parse_in64(request::MASS_EARTH))]
    mass: Option<f64>,

    /// Iron share of the rock and iron, in [0, 0.9] (Earth: 0.325,
    /// Mercury: about 0.7) [default: the archetype's, else drawn from the
    /// star's metallicity]
    #[arg(long, value_parser = parse_in64(request::CORE_MASS_FRACTION))]
    core_fraction: Option<f64>,

    /// Water and ices in Earth oceans (1.4e21 kg each), in [0, 1000000];
    /// more than the planet weighs is refused [default: the archetype's,
    /// else drawn from the distance to the ice line]
    #[arg(long, value_parser = parse_in64(request::WATER_OCEANS))]
    water: Option<f64>,

    /// Hydrogen and helium share of the mass at formation, in [0, 0.999]
    /// (Jupiter: about 0.95) [default: the archetype's, else drawn from the
    /// mass]
    #[arg(long, value_parser = parse_in64(request::ENVELOPE_FRACTION))]
    envelope: Option<f64>,

    /// CO₂ as a factor on the formation rule, in [0, 100]: 1 typical, 0
    /// none [default: the archetype's, else drawn about 1]
    #[arg(long, value_parser = parse_in64(request::VOLATILE_FACTOR))]
    co2: Option<f64>,

    /// N₂ as a factor on the formation rule, in [0, 100]: 1 typical, 0
    /// none [default: the archetype's, else drawn about 1]
    #[arg(long, value_parser = parse_in64(request::VOLATILE_FACTOR))]
    n2: Option<f64>,

    /// Radiogenic abundance at formation, Earth's = 1, in [0.1, 10]: more
    /// internal heat, more volcanism [default: the archetype's, else drawn
    /// about 1]
    #[arg(long, value_parser = parse_in64(request::RADIOGENIC))]
    radiogenic: Option<f64>,

    /// Life: `yes`, it arises wherever the world allows it; `no`, never
    /// [default: the archetype's, else drawn]
    #[arg(long, value_parser = parse_yes_no)]
    life: Option<bool>,

    /// Axial tilt in degrees, in [0, 90] [default: the archetype's, else
    /// random in 5..40, or 0..85 on a planet without a large moon to steady
    /// it]
    #[arg(long, value_parser = parse_in(request::AXIAL_TILT_DEG))]
    axial_tilt: Option<f32>,

    /// Spectral type of the host star, O3V to M9.5V (the Sun: G2V)
    /// [default: the archetype's, else drawn with the frequencies of the
    /// solar neighbourhood, three quarters M dwarfs]
    #[arg(long)]
    star: Option<String>,

    /// Semi-major axis of the orbit in AU, in [0.005, 1000] (Earth: 1,
    /// Mars: 1.524) [default: from the archetype's light or period, else a
    /// position in the habitable zone]
    #[arg(long, value_parser = parse_in(request::ORBIT_AU), conflicts_with = "hz_position")]
    orbit_au: Option<f32>,

    /// Position of the orbit in the star's habitable zone, in [-2, 6]: 0 at
    /// its inner edge, 1 at its outer edge (Earth: about 0.09)
    /// [default: random in 0.1..0.9, unless the archetype sets the orbit]
    #[arg(long, allow_negative_numbers = true, value_parser = parse_in(request::HZ_POSITION))]
    hz_position: Option<f32>,

    /// Eccentricity of the orbit, in [0, 0.9]: 0 circular (Earth: 0.017,
    /// Mercury: 0.206); it raises the light received over a year by
    /// 1/sqrt(1 − e²) [default: the archetype's, else drawn like the planets
    /// known, 0 for the closest planets, whose orbits the tides have
    /// circularised]
    #[arg(long, value_parser = parse_in(request::ECCENTRICITY))]
    eccentricity: Option<f32>,

    /// Longitude of the orbit's perihelion, in degrees from the spring
    /// equinox, in [0, 360] (Earth: 283, Mars: 251): where in the seasons
    /// the planet is closest to its star; on an eccentric orbit it makes
    /// the seasons uneven [default: drawn from the seed]
    #[arg(long, value_parser = parse_in(request::PERIHELION_LONGITUDE_DEG))]
    perihelion: Option<f32>,

    /// Age of the star, in Gyr, above 0 and at most its main-sequence life
    /// (about 10 Gyr for the Sun): the older it is, the more planets its
    /// tides have locked and the more its giants have cooled. With --system
    /// the whole system shares it [default: drawn from the seed, between
    /// 0.5 and 10 Gyr, or the star's life if shorter; a star drawn at
    /// random is redrawn until it lives that long]
    #[arg(long)]
    age: Option<f32>,

    /// Epoch of the plates in Ma from the present, in [-300, 300], negative
    /// in the past: on worlds with plate tectonics, the continents as the
    /// plates have carried them by then (or will have). The world is written
    /// to `<planet>-past<N>ma-<seed>` or `<planet>-future<N>ma-<seed>`
    /// [default: 0, the present]
    #[arg(long, allow_hyphen_values = true, value_parser = parse_in(request::DRIFT_MA))]
    drift: Option<f32>,

    /// Moons: `auto`, those the seed draws (about one rocky planet in 12
    /// has a large moon, small worlds often a companion, others small
    /// debris or captured moons, planets despun by their star only moonlets
    /// light enough to last),
    /// `none`, or a number from 1 to 6: that many moons, the star and orbit
    /// drawn again if they leave no room for them [default: auto]
    #[arg(long)]
    moons: Option<MoonsMode>,

    /// Metallicity of the star, [Fe/H] in dex, in [-1, 0.5]: 0 the Sun's;
    /// every 0.1 dex more makes gas giants about 1.6 times more likely
    /// [default: drawn like the stars nearby]
    #[arg(long, allow_hyphen_values = true, value_parser = parse_in(request::METALLICITY))]
    metallicity: Option<f32>,

    /// Giant planets in the system: `auto`, those the seed draws (about one
    /// Sun-like star in four has a gas giant, fewer around red dwarfs, more
    /// around metal-rich stars), or `none`, not modelled [default: auto]
    #[arg(long)]
    giants: Option<GiantsMode>,

    /// The moon of a giant: `auto`, as the seed draws (one rocky world in
    /// 50), `giant` (always: an Earth-sized moon of a 0.3 to 10 Jupiter-mass
    /// giant, heated by its tides) or `none` [default: auto]
    #[arg(long)]
    host: Option<HostMode>,

    /// A lone planet: the system drawn round the planet (the one written
    /// to --systems-dir, whose id then carries `-lone-`) holds only its
    /// star, the planet and its moons (or the giant it orbits), with no
    /// belt; the planet is generated with no giant neighbours, whatever
    /// --giants says
    #[arg(long)]
    alone: bool,

    /// Noise seed [default: random]
    #[arg(long)]
    seed: Option<u32>,

    /// Map width in pixels
    #[arg(long, default_value_t = request::fallback::WIDTH,
          value_parser = clap::value_parser!(u32).range(2..=16384))]
    width: u32,

    /// Map height in pixels
    #[arg(long, default_value_t = request::fallback::HEIGHT,
          value_parser = clap::value_parser!(u32).range(2..=16384))]
    height: u32,

    /// Skip the diagnostic noise maps (noise_maps/), and the time and memory
    /// they take. Also set by MAPGEN_NO_NOISE_MAPS: true/false, 1/0, yes/no,
    /// on/off
    #[arg(long, env = "MAPGEN_NO_NOISE_MAPS",
          value_parser = clap::builder::BoolishValueParser::new())]
    no_noise_maps: bool,

    /// Skip world.svg, the vector image of the map. The web app does not
    /// write it either: it draws it on request ("SVG" in the world card).
    /// Also set by MAPGEN_NO_SVG: true/false, 1/0, yes/no, on/off
    #[arg(long, env = "MAPGEN_NO_SVG",
          value_parser = clap::builder::BoolishValueParser::new())]
    no_svg: bool,

    /// Draws a whole system (see docs/system-spec.md) instead of a world:
    /// the planets asked by archetype, `earth-like=2,jupiter-like=1`
    /// (each sits at its archetype's insolation or period, with its mass
    /// and inputs; names: see --list-planets; 15 planets at most), or
    /// `auto` for a drawn system; with --star, --metallicity, --seed and
    /// the map size. A moon archetype (titan-like, europa-like,
    /// ganymede-like, callisto-like, io-like, triton-like,
    /// enceladus-like) rides a giant of its host's archetype asked in the
    /// same list that can carry it (`saturn-like=1,titan-like=1`: one
    /// Saturn with its Titan), or brings one, counted among the 15.
    /// Without --star such a system takes its host's star (G2V); a star
    /// named is honoured, and an asked moon around a red dwarf may lose
    /// its air
    #[arg(long)]
    system: Option<String>,

    /// Draws the system (the whole system of --system, or the one around
    /// the planet asked) and writes only its system.json into
    /// <systems-dir>/<id>/, no maps; prints its bodies
    #[arg(long)]
    draw_only: bool,

    /// Directory that receives the drawn systems
    #[arg(long, default_value = "systems")]
    systems_dir: PathBuf,

    /// Generates the maps of a body of the system (`c`, `c-1`) and of its
    /// neighbourhood (a planet and its moons; a moon, its planet and the
    /// planet's other moons), with --system, --draw-only or --in-system
    #[arg(long)]
    body: Option<String>,

    /// The system (its id, in --systems-dir) --body generates in, instead
    /// of drawing one
    #[arg(long, requires = "body")]
    in_system: Option<String>,

    /// Generates another resolution, `WxH` (`4096x2048`), of --body of
    /// --in-system, generated already: the same world at that size, into
    /// bodies/<body>/sizes/<WxH>/ beside its other resolutions
    #[arg(long, requires_all = ["in_system", "body"], value_parser = parse_size)]
    size: Option<(u32, u32)>,
}

/// A resolution of `--size`: `WxH`, each between the map size limits.
fn parse_size(text: &str) -> Result<(u32, u32), String> {
    use mapgen::request::MAP_SIZE;
    let (width, height) = mapgen::sizes::parse_size_name(text)
        .ok_or_else(|| format!("{text:?}: expected WxH, such as 4096x2048"))?;
    if !(MAP_SIZE.0..=MAP_SIZE.1).contains(&width) || !(MAP_SIZE.0..=MAP_SIZE.1).contains(&height) {
        return Err(format!(
            "{text}: width and height must be between {} and {}",
            MAP_SIZE.0, MAP_SIZE.1
        ));
    }
    Ok((width, height))
}

/// The planets of `--system`: `archetype=count` pairs, or `auto`.
fn parse_planets(text: &str) -> Result<Option<std::collections::BTreeMap<String, u32>>, String> {
    if text == "auto" {
        return Ok(None);
    }
    let mut planets = std::collections::BTreeMap::new();
    for pair in text.split(',').filter(|p| !p.trim().is_empty()) {
        let (archetype, count) = pair
            .split_once('=')
            .ok_or_else(|| format!("{pair:?}: expected archetype=count"))?;
        let count: u32 = count.trim().parse().map_err(|e| format!("{pair:?}: {e}"))?;
        *planets.entry(archetype.trim().to_string()).or_insert(0) += count;
    }
    Ok(Some(planets))
}

impl Args {
    /// The extra files to write: both by default, as a command-line user
    /// expects the whole output (the web server writes neither).
    fn diagnostics(&self) -> Diagnostics {
        Diagnostics {
            svg: !self.no_svg,
            noise_maps: !self.no_noise_maps,
        }
    }
}

/// Generates `body` and its neighbourhood in the system written in `dir`.
fn generate_body(
    dir: &std::path::Path,
    body: &str,
    diagnostics: Diagnostics,
) -> Result<(), Box<dyn Error>> {
    let mut last = None;
    let done = mapgen::system::generate_neighbourhood_with(dir, body, diagnostics, |p| {
        if last.as_ref() != Some(&(p.body.clone(), p.step)) {
            eprintln!(
                "[{}/{}] {} — {:?} ({}/{})",
                p.body_step, p.bodies, p.body, p.stage, p.step, p.steps
            );
            last = Some((p.body.clone(), p.step));
        }
    })?;
    if done.is_empty() {
        println!("{body} and its neighbourhood are generated already");
    } else {
        println!(
            "Generated: {} → {}",
            done.join(", "),
            dir.join("bodies").display()
        );
    }
    Ok(())
}

/// Generates the `width` × `height` resolution of `body` in the system
/// written in `dir` (see `--size`).
fn generate_size(
    dir: &std::path::Path,
    body: &str,
    (width, height): (u32, u32),
    diagnostics: Diagnostics,
) -> Result<(), Box<dyn Error>> {
    let mut last = None;
    mapgen::system::generate_size(dir, body, width, height, diagnostics, |p| {
        if last != Some(p.step) {
            eprintln!(
                "{} {width}x{height} — {:?} ({}/{})",
                p.body, p.stage, p.step, p.steps
            );
            last = Some(p.step);
        }
    })?;
    println!(
        "Generated: {body} at {width}x{height} → {}",
        mapgen::sizes::size_dir(&dir.join("bodies").join(body), width, height).display()
    );
    Ok(())
}

/// Draws a system and writes its system.json (see `--draw-only`); then
/// generates `body` when given.
fn draw_system(
    request: mapgen::system::SystemRequest,
    dir: &std::path::Path,
    body: Option<&str>,
    diagnostics: Diagnostics,
) -> Result<(), Box<dyn Error>> {
    use mapgen::system::{draw, system_id, write_system};
    let system = draw(&request, &mut rand::rng())?;
    let id = system_id(&system);
    write_system(&dir.join(&id), &system)?;
    print_bodies(&system);
    println!("→ {}", dir.join(&id).join("system.json").display());
    match body {
        Some(body) => generate_body(&dir.join(&id), body, diagnostics),
        None => Ok(()),
    }
}

/// Prints a system's bodies, one line each (moons under their planet).
fn print_bodies(system: &mapgen::system::System) {
    use mapgen::system::BodyKind;
    let id = mapgen::system::system_id(system);
    println!(
        "System {id}: {} ({}, {:.1} Gyr), {} planets, {} moons",
        system.star.designation,
        system.star.spectral,
        system.star.info.age_gyr,
        system
            .bodies
            .iter()
            .filter(|b| b.kind == BodyKind::Planet)
            .count(),
        system
            .bodies
            .iter()
            .filter(|b| b.kind == BodyKind::Moon)
            .count(),
    );
    for body in &system.bodies {
        let indent = if body.kind == BodyKind::Moon {
            "    "
        } else {
            "  "
        };
        let distance = if body.kind == BodyKind::Planet {
            format!("{:.3} AU", body.orbit.semi_major_axis_au)
        } else {
            format!("{:.0} km", body.orbit.semi_major_axis_km)
        };
        println!(
            "{indent}{:5} {:24} {:18} {distance:>11}  r={:.0} km  {:.1} K",
            body.id,
            body.designation,
            body.body_type,
            body.physical.radius_km,
            body.surroundings.equilibrium_k
        );
    }
}

/// Builds a clap value parser that accepts an `f64` within `limits`.
fn parse_in64(limits: Limits) -> impl Fn(&str) -> Result<f64, String> + Clone {
    move |s| {
        let v: f64 = s.parse().map_err(|e| format!("{e}"))?;
        if (f64::from(limits.min)..=f64::from(limits.max)).contains(&v) {
            Ok(v)
        } else {
            Err(format!("must be between {} and {}", limits.min, limits.max))
        }
    }
}

/// `yes` or `no` (also `true`/`false`).
fn parse_yes_no(s: &str) -> Result<bool, String> {
    match s {
        "yes" | "true" => Ok(true),
        "no" | "false" => Ok(false),
        _ => Err(format!("{s:?}: expected yes or no")),
    }
}

/// Builds a clap value parser that accepts an `f32` within `limits`.
fn parse_in(limits: Limits) -> impl Fn(&str) -> Result<f32, String> + Clone {
    move |s| {
        let v: f32 = s.parse().map_err(|e| format!("{e}"))?;
        if limits.contains(v) {
            Ok(v)
        } else {
            Err(format!("must be between {} and {}", limits.min, limits.max))
        }
    }
}

fn main() -> ExitCode {
    match run(Args::parse()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(args: Args) -> Result<(), Box<dyn Error>> {
    if args.list_planets {
        for archetype in Archetype::built_in() {
            println!("{:14} {}", archetype.name, archetype.description);
        }
        return Ok(());
    }

    let diagnostics = args.diagnostics();
    if let (Some(system), Some(body), Some(size)) = (&args.in_system, &args.body, args.size) {
        return generate_size(&args.systems_dir.join(system), body, size, diagnostics);
    }
    if let Some(planets) = &args.system {
        let request = mapgen::system::SystemRequest::System(mapgen::system::WholeSystemRequest {
            star: args.star.clone(),
            metallicity: args.metallicity,
            age_gyr: args.age,
            planets: parse_planets(planets)?,
            seed: args.seed,
            width: Some(args.width),
            height: Some(args.height),
        });
        return draw_system(
            request,
            &args.systems_dir,
            args.body.as_deref(),
            diagnostics,
        );
    }
    if let (Some(system), Some(body)) = (&args.in_system, &args.body) {
        return generate_body(&args.systems_dir.join(system), body, diagnostics);
    }

    let request = WorldRequest {
        planet: args.planet,
        seed: args.seed,
        axial_tilt_deg: args.axial_tilt,
        star: args.star,
        orbit_au: args.orbit_au,
        hz_position: args.hz_position,
        eccentricity: args.eccentricity,
        perihelion_longitude_deg: args.perihelion,
        age_gyr: args.age,
        drift_ma: args.drift,
        moons: args.moons,
        metallicity: args.metallicity,
        giants: args.giants,
        mass_earth: args.mass,
        core_mass_fraction: args.core_fraction,
        water_oceans: args.water,
        envelope_fraction: args.envelope,
        co2: args.co2,
        n2: args.n2,
        radiogenic: args.radiogenic,
        life: args.life,
        host: args.host,
        alone: args.alone.then_some(true),
        width: Some(args.width),
        height: Some(args.height),
    };
    if args.draw_only {
        return draw_system(
            mapgen::system::SystemRequest::Around(request),
            &args.systems_dir,
            args.body.as_deref(),
            diagnostics,
        );
    }
    let resolved = request.resolve(&mut rand::rng())?;
    if !resolved.ignored.is_empty() {
        eprintln!(
            "warning: ignored, this planet has no use for: {}",
            resolved.ignored.join(", ")
        );
    }
    let p = &resolved.params;
    let model = resolved.model();
    let star = StarInfo::new(p.star, p.orbit_au, p.eccentricity, p.age_gyr);
    // The class and the regime the model derived (a giant keeps its
    // envelope and has none).
    let regime = model
        .surface
        .as_ref()
        .map_or("no surface", |s| s.regime.label());
    println!(
        "Planet → {} ({}) seed={} mass={:.3} M⊕ radius={:.3} R⊕ gravity≈{:.2}g \
         core={:.3} water={:.3} oceans envelope={:.4} life={} ({regime})",
        model.class.key(),
        resolved
            .params
            .archetype
            .as_deref()
            .unwrap_or("no archetype"),
        p.seed,
        model.inputs.mass_earth,
        model.interior.radius_earth,
        model.interior.gravity,
        model.inputs.core_mass_fraction,
        model.surface.as_ref().map_or(0.0, |s| s.water.oceans),
        model.inputs.envelope_fraction,
        model.surface.as_ref().is_some_and(|s| s.life.arose),
    );
    println!(
        "World → circumference={:.0} km tilt={:.1}° pressure={:.3} bar volcanic={:.2} \
         erosion={:.2} surface_age={:.2} Ga{} star={} age={:.2} Gyr orbit={:.3} AU e={:.3} \
         ({:.2} in the habitable zone, {:.2}× Earth's light)",
        p.circumference_km,
        p.axial_tilt_deg,
        p.pressure_bar,
        p.volcanic_intensity,
        p.erosion,
        p.surface_age_ga,
        if p.drift_ma == 0.0 {
            String::new()
        } else {
            format!(" drift={} Ma", p.drift_ma)
        },
        star.kind,
        star.age_gyr,
        star.orbit_au,
        star.eccentricity,
        star.hz_position,
        star.insolation,
    );

    let names = mapgen::naming::of_params(p);
    println!("Name → {} (star {})", names.world, names.star);
    if let Some(system) = MoonSystem::draw(p) {
        println!("Moons → {}", moons_summary(&system));
    }
    if let Some(giant) = mapgen::giant_world::info(p) {
        println!(
            "Giant → {:.1} Earth masses ({:.2} MJ), {:.1} Earth radii, {:.2} g/cm³, day {:.1} h, \
             flattening {:.3}, Teff {:.0} K (class {}), {} eastward jets per hemisphere, winds {:.0} to {:.0} m/s{}",
            giant.mass_earth,
            giant.mass_earth / JUPITER_EARTH_MASSES,
            giant.radius_earth,
            giant.density,
            giant.rotation_hours,
            giant.flattening,
            giant.effective_k,
            giant.class,
            giant.jets,
            -giant.wind_west,
            giant.wind_east,
            match &giant.rings {
                Some(r) if r.bright => ", bright rings",
                Some(_) => ", faint rings",
                None => "",
            }
        );
    }
    if let Some(host) = HostGiant::draw(p) {
        println!(
            "Host → the moon of a {:.2} MJ giant, {:.1} of its radii out ({:.0} km), day {:.2} days, \
             tides {:.2} W/m², the giant {:.1}° wide in the sky{}",
            host.giant.mass_earth / JUPITER_EARTH_MASSES,
            host.distance_radii,
            host.distance_km,
            host.period_days,
            host.tidal_flux,
            host.angular_diameter_deg,
            if host.inside_edge {
                ", inside the habitable edge (runaway greenhouse)"
            } else {
                ""
            }
        );
    }
    if let Some(system) = GiantSystem::draw(p) {
        println!("Giants → {}", giants_summary(&system, p.metallicity));
    }
    // The system around it, the planet as shown above; drawn again into the
    // same directory, it replaces the one there.
    let system = mapgen::system::draw_around_params(
        &request,
        resolved.params.clone(),
        resolved.model().clone(),
    );
    let id = mapgen::system::system_id(&system);
    let dir = args.systems_dir.join(&id);
    // The names given in the web app are kept.
    let names = std::fs::read(dir.join("names.json")).ok();
    if dir.exists() {
        std::fs::remove_dir_all(&dir)?;
    }
    if let Some(names) = names {
        std::fs::create_dir_all(&dir)?;
        std::fs::write(dir.join("names.json"), names)?;
    }
    mapgen::system::write_system(&dir, &system)?;
    print_bodies(&system);
    let focus = system
        .focus
        .clone()
        .ok_or("the system has no planet asked for")?;
    let body = args.body.as_deref().unwrap_or(&focus);
    generate_body(&dir, body, diagnostics)?;
    // Exact values (the summary above is rounded) so the world can be
    // regenerated; the size too, since the relief depends on the resolution.
    // Every value pinned, as the export of a system around a planet pins
    // them; the defaults left out.
    let pinned = request.pinned(p, Some(model));
    let set = |value: Option<f32>| value.expect("pinned");
    let set64 = |value: Option<f64>| value.expect("pinned");
    let mut reproduce = Vec::new();
    if let Some(planet) = &pinned.planet {
        reproduce.push(format!("--planet {planet}"));
    }
    reproduce.extend([
        format!("--seed {}", pinned.seed.expect("pinned")),
        format!("--mass {}", set64(pinned.mass_earth)),
        format!("--core-fraction {}", set64(pinned.core_mass_fraction)),
        format!("--radiogenic {}", set64(pinned.radiogenic)),
    ]);
    // The formation inputs (`PlanetModel::formation`), so that the planet
    // stays the same under another seed too.
    for (flag, value) in [
        ("--water", pinned.water_oceans),
        ("--envelope", pinned.envelope_fraction),
        ("--co2", pinned.co2),
        ("--n2", pinned.n2),
    ] {
        if let Some(value) = value {
            reproduce.push(format!("{flag} {value}"));
        }
    }
    if let Some(life) = pinned.life {
        reproduce.push(format!("--life {}", if life { "yes" } else { "no" }));
    }
    reproduce.extend([
        format!("--axial-tilt {}", set(pinned.axial_tilt_deg)),
        format!("--star {}", pinned.star.as_deref().expect("pinned")),
    ]);
    match (pinned.orbit_au, pinned.hz_position) {
        (Some(orbit), _) => reproduce.push(format!("--orbit-au {orbit}")),
        (None, Some(position)) => reproduce.push(format!("--hz-position {position}")),
        (None, None) => {}
    }
    reproduce.extend([
        format!("--eccentricity {}", set(pinned.eccentricity)),
        format!("--metallicity {}", set(pinned.metallicity)),
        format!("--age {}", set(pinned.age_gyr)),
    ]);
    if let Some(longitude) = pinned
        .perihelion_longitude_deg
        .filter(|_| p.eccentricity > 0.0)
    {
        reproduce.push(format!("--perihelion {longitude}"));
    }
    if let Some(drift) = pinned.drift_ma.filter(|d| *d != 0.0) {
        reproduce.push(format!("--drift {drift}"));
    }
    if request.alone == Some(true) {
        reproduce.push("--alone".into());
    } else if pinned.giants == Some(GiantsMode::None) {
        reproduce.push("--giants none".into());
    }
    match pinned.host {
        Some(HostMode::Giant) => reproduce.push("--host giant".into()),
        Some(HostMode::None) => reproduce.push("--host none".into()),
        _ => {}
    }
    match pinned.moons {
        Some(MoonsMode::None) => reproduce.push("--moons none".into()),
        Some(MoonsMode::Count(n)) => reproduce.push(format!("--moons {n}")),
        _ => {}
    }
    reproduce.push(format!("--width {}", pinned.width.expect("pinned")));
    reproduce.push(format!("--height {}", pinned.height.expect("pinned")));
    println!("Reproduce with: {}", reproduce.join(" "));
    Ok(())
}

/// One line on a system's giants: each one's letter, kind, mass and orbit,
/// and what they do to the world.
fn giants_summary(system: &GiantSystem, metallicity: f32) -> String {
    let giants = if system.giants.is_empty() {
        "none".to_string()
    } else {
        system
            .giants
            .iter()
            .map(|g| {
                format!(
                    "{} ({}{}, {:.2} MJ, {:.2} AU, e={:.2})",
                    g.name,
                    if g.hot { "hot " } else { "" },
                    match g.kind {
                        GiantKind::Gas => "gas giant",
                        GiantKind::Ice => "ice giant",
                    },
                    g.mass_earth / JUPITER_EARTH_MASSES,
                    g.orbit_au,
                    g.eccentricity,
                )
            })
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!(
        "{giants}; [Fe/H]={metallicity:+.2}, forced e={:.3}, impacts ×{:.2}",
        system.forced_eccentricity, system.impact_factor
    )
}

/// One line on a world's moons: each one's name, origin, size and orbit.
fn moons_summary(system: &MoonSystem) -> String {
    if system.moons.is_empty() {
        return "none".into();
    }
    let moons: Vec<String> = system
        .moons
        .iter()
        .map(|m| {
            let origin = match m.origin {
                MoonOrigin::GiantImpact => "giant impact",
                MoonOrigin::Disk => "disk",
                MoonOrigin::Debris => "debris",
                MoonOrigin::Captured => "captured",
            };
            format!(
                "{} ({origin}, {:.0} km{}, {:.1} planet radii, {:.2} d)",
                m.name,
                m.radius_km,
                if m.round { "" } else { ", irregular" },
                m.semi_major_axis_radii,
                m.period_days
            )
        })
        .collect();
    format!(
        "{}{}",
        moons.join(", "),
        if system.binary {
            "; a binary planet"
        } else {
            ""
        }
    )
}
