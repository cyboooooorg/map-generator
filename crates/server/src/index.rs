    #[test]
    fn a_body_remembers_its_last_opening_and_its_generator() {
        let root = temp_root("opened");
        let systems = root.join("systems");
        tree(&systems, &["mgs-1-1"]);
        let index = Index::open(&root.join("mapgen.sqlite")).unwrap();
        index.reconcile(&systems).unwrap();

        assert_eq!(index.last_opened("mgs-1-1", "c").unwrap(), None);
        assert!(index.touch_body("mgs-1-1", "c").unwrap());
        let first = index.last_opened("mgs-1-1", "c").unwrap().unwrap();
        assert!(first > 0);
        // Not written again within the minute.
        assert!(!index.touch_body("mgs-1-1", "c").unwrap());
        index.write_opened("mgs-1-1", "c", first + 5).unwrap();
        assert_eq!(index.last_opened("mgs-1-1", "c").unwrap(), Some(first + 5));
        // An unknown body is no error.
        index.write_opened("mgs-1-1", "zz", 1).unwrap();

        // Read again from the tree, the date and the generator stay; a
        // body generated since is made by this generator.
        let json = SYSTEM.replace(
            r#""designation": "MGS 48213 b", "generated": false"#,
            r#""designation": "MGS 48213 b", "generated": true"#,
        );
        std::thread::sleep(Duration::from_millis(20));
        std::fs::write(systems.join("mgs-1-1/system.json"), json).unwrap();
        index
            .refresh_system(&systems, "mgs-1-1", Cause::Generated)
            .unwrap();
        assert_eq!(index.last_opened("mgs-1-1", "c").unwrap(), Some(first + 5));
        assert_eq!(
            index.generator_of("mgs-1-1", "c").unwrap().unwrap().format,
            Some(9)
        );
        assert_eq!(
            index.generator_of("mgs-1-1", "b").unwrap(),
            Some(GeneratorOf {
                version: Some(GENERATOR_VERSION.to_string()),
                format: Some(GENERATOR_FORMAT),
            })
        );

        // Drawn again, the system starts over.
        index
            .refresh_system(&systems, "mgs-1-1", Cause::Drawn)
            .unwrap();
        assert_eq!(index.last_opened("mgs-1-1", "c").unwrap(), None);
        std::fs::remove_dir_all(root).unwrap();
    }

