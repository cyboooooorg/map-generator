    #[test]
    fn jobs_survive_a_reopen_and_the_unfinished_ones_are_interrupted() {
        let root = temp_root("jobs");
        let db = root.join("mapgen.sqlite");
        let index = Index::open(&db).unwrap();
        let request = WorldRequest::default();
        for id in 1..=4 {
            index
                .job_queued(id, "mgs-1-1", Some(("mgs-1-1", "c")), &request, 20)
                .unwrap();
        }
        index
            .job_status(
                1,
                &JobStatus::Done {
                    world_id: "mgs-1-1".into(),
                    bodies: vec!["c".into(), "c-1".into()],
                },
            )
            .unwrap();
        index.job_status(2, &JobStatus::Cancelled).unwrap();
        index
            .job_status(
                3,
                &JobStatus::Failed {
                    error: "boom".into(),
                },
            )
            .unwrap();
        let running = JobStatus::Running {
            stage: mapgen::generation::Stage::ALL[0],
            step: 1,
            steps: 8,
            body: Some("c".into()),
            body_step: Some(1),
            bodies: Some(2),
        };
        index.job_status(4, &running).unwrap();
        drop(index);

        let index = Index::open(&db).unwrap();
        assert_eq!(index.next_job_id().unwrap(), 5);
        assert_eq!(index.interrupt_unfinished().unwrap(), 1);
        assert_eq!(index.interrupt_unfinished().unwrap(), 0);
        let jobs = index.jobs().unwrap();
        assert_eq!(
            jobs.iter().map(|j| j.id).collect::<Vec<_>>(),
            [4, 3, 2, 1],
            "newest first"
        );
        assert_eq!(
            jobs[0].status,
            JobStatus::Failed {
                error: INTERRUPTED.into()
            }
        );
        assert_eq!(
            jobs[1].status,
            JobStatus::Failed {
                error: "boom".into()
            }
        );
        assert_eq!(jobs[2].status, JobStatus::Cancelled);
        assert_eq!(
            jobs[3].status,
            JobStatus::Done {
                world_id: "mgs-1-1".into(),
                bodies: vec!["c".into(), "c-1".into()]
            }
        );
        assert_eq!(jobs[0].system, Some(("mgs-1-1".into(), "c".into())));

        // Only the newest finished jobs are kept.
        index.job_queued(5, "mgs-1-1", None, &request, 2).unwrap();
        let kept: Vec<u64> = index.jobs().unwrap().iter().map(|j| j.id).collect();
        assert_eq!(kept, [5, 4, 3]);
        std::fs::remove_dir_all(root).unwrap();
    }

