    /// Brings the index in line with the tree under `root`: systems found
    /// there and not here are added, those whose `system.json` or
    /// `names.json` changed are read again, those gone from disk are
    /// dropped. On an empty database this is the rebuild.
    pub fn reconcile(&self, root: &Path) -> Result<Reconciled> {
        let known: HashMap<String, (u64, Option<u64>)> = {
            let conn = self.conn();
            let mut stmt =
                conn.prepare("SELECT id, modified_ms, names_modified_ms FROM systems")?;
            stmt.query_map([], |r| {
                Ok((
                    r.get::<_, String>(0)?,
                    (
                        r.get::<_, i64>(1)? as u64,
                        r.get::<_, Option<i64>>(2)?.map(|v| v as u64),
                    ),
                ))
            })?
            .collect::<rusqlite::Result<_>>()?
        };
        let mut report = Reconciled::default();
        let mut on_disk = HashSet::new();
        for id in systems::system_ids(root) {
            let dir = systems::system_dir(root, &id);
            let Some(modified) = systems::modified_ms(&dir.join(systems::SYSTEM_FILE)) else {
                continue;
            };
            let names_modified = systems::modified_ms(&dir.join(systems::NAMES_FILE));
            let current = match known.get(&id) {
                Some(&(stored, stored_names)) => {
                    stored == modified
                        && (names_modified.is_none() || names_modified == stored_names)
                }
                None => false,
            };
            if current {
                on_disk.insert(id);
                continue;
            }
            if self.refresh_system(root, &id, Cause::Scan)? {
                on_disk.insert(id.clone());
                if known.contains_key(&id) {
                    report.updated += 1;
                } else {
                    report.added += 1;
                }
            }
        }
        for id in known.keys().filter(|id| !on_disk.contains(*id)) {
            self.remove_system(id)?;
            report.removed += 1;
        }
        Ok(report)
    }

    /// Reads system `id` again from the tree under `root` into the index;
    /// false (and the system dropped from the index) when its
    /// `system.json` is missing or unreadable.
    pub fn refresh_system(&self, root: &Path, id: &str, cause: Cause) -> Result<bool> {
        let Some(loaded) = load(root, id) else {
            self.remove_system(id)?;
            return Ok(false);
        };
        let mut conn = self.conn();
        let tx = conn.transaction()?;
        store(&tx, &loaded, cause)?;
        tx.commit()?;
        Ok(true)
    }

    /// Drops system `id` (its bodies and names with it). Its jobs stay in
    /// the history.
    pub fn remove_system(&self, id: &str) -> Result<()> {
        self.conn()
            .execute("DELETE FROM systems WHERE id = ?1", [id])?;
        self.touched
            .lock()
            .expect("touched lock")
            .retain(|(system, _), _| system != id);
        Ok(())
    }

    /// Every system, most recently drawn first, as `GET /api/systems`
    /// lists them.
    pub fn list_systems(&self) -> Result<Vec<SystemSummary>> {
        self.summaries(None)
    }

    /// One system's summary.
    pub fn summary(&self, id: &str) -> Result<Option<SystemSummary>> {
        Ok(self.summaries(Some(id))?.pop())
    }

    fn summaries(&self, only: Option<&str>) -> Result<Vec<SystemSummary>> {
        let conn = self.conn();
        let filter = if only.is_some() {
            "WHERE id = ?1"
        } else {
            "WHERE ?1 IS NULL"
        };
        let mut stmt = conn.prepare(&format!(
            "SELECT id, seed, width, height, star, designation, light_r, light_g, light_b,
                    hz_inner_au, hz_outer_au, modified_ms
             FROM systems {filter} ORDER BY modified_ms DESC, id"
        ))?;
        let mut systems: Vec<SystemSummary> = stmt
            .query_map([only], |r| {
                Ok(SystemSummary {
                    id: r.get(0)?,
                    seed: r.get(1)?,
                    width: r.get(2)?,
                    height: r.get(3)?,
                    star: r.get(4)?,
                    designation: r.get(5)?,
                    star_light: [r.get(6)?, r.get(7)?, r.get(8)?],
                    hz_inner_au: r.get(9)?,
                    hz_outer_au: r.get(10)?,
                    planets: BTreeMap::new(),
                    moons: 0,
                    bodies: Vec::new(),
                    names: BTreeMap::new(),
                    modified_ms: r.get::<_, i64>(11)? as u64,
                })
            })?
            .collect::<rusqlite::Result<_>>()?;
        let at: HashMap<String, usize> = systems
            .iter()
            .enumerate()
            .map(|(i, s)| (s.id.clone(), i))
            .collect();

        let mut stmt = conn.prepare(
            "SELECT system_id, id, designation, kind, body_type, colour_r, colour_g, colour_b,
                    generated, orbit_au, eccentricity, periapsis_deg
             FROM bodies WHERE ?1 IS NULL OR system_id = ?1 ORDER BY system_id, position",
        )?;
        let rows = stmt.query_map([only], |r| {
            Ok((
                r.get::<_, String>(0)?,
                BodySummary {
                    id: r.get(1)?,
                    designation: r.get(2)?,
                    kind: r.get(3)?,
                    body_type: r.get(4)?,
                    colour: [r.get(5)?, r.get(6)?, r.get(7)?],
                    generated: r.get(8)?,
                    orbit_au: r.get(9)?,
                    eccentricity: r.get(10)?,
                    periapsis_deg: r.get(11)?,
                },
            ))
        })?;
        for row in rows {
            let (system, body) = row?;
            if let Some(&i) = at.get(&system) {
                let s = &mut systems[i];
                match body.kind.as_str() {
                    "planet" => *s.planets.entry(body.body_type.clone()).or_default() += 1,
                    "moon" => s.moons += 1,
                    _ => {}
                }
                s.bodies.push(body);
            }
        }

        let mut stmt = conn.prepare(
            "SELECT system_id, body_id, name FROM names WHERE ?1 IS NULL OR system_id = ?1",
        )?;
        let rows = stmt.query_map([only], |r| {
            Ok((
                r.get::<_, String>(0)?,
                r.get::<_, String>(1)?,
                r.get::<_, String>(2)?,
            ))
        })?;
        for row in rows {
            let (system, body, name) = row?;
            if let Some(&i) = at.get(&system) {
                systems[i].names.insert(body, name);
            }
        }
        Ok(systems)
    }

