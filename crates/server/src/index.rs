    /// The names given to system `id`.
    pub fn names(&self, id: &str) -> Result<GivenNames> {
        let conn = self.conn();
        let mut stmt = conn.prepare("SELECT body_id, name FROM names WHERE system_id = ?1")?;
        let rows = stmt.query_map([id], |r| Ok((r.get(0)?, r.get(1)?)))?;
        Ok(rows.collect::<rusqlite::Result<_>>()?)
    }

    /// Gives the bodies of system `id` the names `given`, replacing those
    /// they had, and returns its summary. The names are checked, written
    /// to `names.json` (the tree stays self-sufficient), then to the
    /// index. No names at all removes the file.
    pub fn give_names(
        &self,
        root: &Path,
        id: &str,
        given: &GivenNames,
    ) -> std::result::Result<SystemSummary, systems::NamingError> {
        let io = |e: IndexError| systems::NamingError::Io(e.to_string());
        let current = self
            .summary(id)
            .map_err(io)?
            .ok_or(systems::NamingError::NotFound)?;
        let names = systems::checked_names(&current.bodies, given)?;
        systems::write_names_file(root, id, &names)?;
        let modified =
            systems::modified_ms(&systems::system_dir(root, id).join(systems::NAMES_FILE));
        {
            let mut conn = self.conn();
            let tx = conn.transaction().map_err(|e| io(e.into()))?;
            replace_names(&tx, id, &names, modified).map_err(|e| io(e.into()))?;
            tx.commit().map_err(|e| io(e.into()))?;
        }
        self.summary(id)
            .map_err(io)?
            .ok_or(systems::NamingError::NotFound)
    }

