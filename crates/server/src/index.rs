    /// Whether the last opened date of a body is due for a write; marks it
    /// written. Cheap, no database access: call it before moving to a
    /// blocking thread for [`Index::write_opened`].
    pub fn touch_due(&self, system: &str, body: &str) -> bool {
        let mut touched = self.touched.lock().expect("touched lock");
        let key = (system.to_string(), body.to_string());
        let now = Instant::now();
        match touched.get(&key) {
            Some(last) if now.duration_since(*last) < TOUCH_EVERY => false,
            _ => {
                touched.insert(key, now);
                true
            }
        }
    }

    /// Records that a body's data was served or opened, at most once a
    /// minute; whether it wrote.
    #[allow(
        dead_code,
        reason = "read by the eviction and regeneration of step 3, tested now"
    )]
    pub fn touch_body(&self, system: &str, body: &str) -> Result<bool> {
        if !self.touch_due(system, body) {
            return Ok(false);
        }
        self.write_opened(system, body, now_ms())?;
        Ok(true)
    }

    /// Sets a body's last opened date.
    pub fn write_opened(&self, system: &str, body: &str, at_ms: u64) -> Result<()> {
        self.conn().execute(
            "UPDATE bodies SET last_opened_ms = ?3 WHERE system_id = ?1 AND id = ?2",
            params![system, body, at_ms as i64],
        )?;
        Ok(())
    }

    /// When a body was last served or opened, ms since the Unix epoch.
    #[allow(
        dead_code,
        reason = "read by the eviction and regeneration of step 3, tested now"
    )]
    pub fn last_opened(&self, system: &str, body: &str) -> Result<Option<u64>> {
        Ok(self
            .conn()
            .query_row(
                "SELECT last_opened_ms FROM bodies WHERE system_id = ?1 AND id = ?2",
                params![system, body],
                |r| r.get::<_, Option<i64>>(0),
            )
            .optional()?
            .flatten()
            .map(|v| v as u64))
    }

    /// The generator a body was made with; `None` when it is not
    /// generated (or unknown).
    #[allow(
        dead_code,
        reason = "read by the eviction and regeneration of step 3, tested now"
    )]
    pub fn generator_of(&self, system: &str, body: &str) -> Result<Option<GeneratorOf>> {
        Ok(self
            .conn()
            .query_row(
                "SELECT generator_version, generator_format FROM bodies
                 WHERE system_id = ?1 AND id = ?2 AND generated = 1",
                params![system, body],
                |r| {
                    Ok(GeneratorOf {
                        version: r.get(0)?,
                        format: r.get::<_, Option<i64>>(1)?.map(|v| v as u32),
                    })
                },
            )
            .optional()?)
    }

    /// What generates a body again: its seed and its parameters (JSON).
    #[allow(
        dead_code,
        reason = "read by the eviction and regeneration of step 3, tested now"
    )]
    pub fn regeneration_of(&self, system: &str, body: &str) -> Result<Option<(u32, String)>> {
        Ok(self
            .conn()
            .query_row(
                "SELECT seed, params FROM bodies WHERE system_id = ?1 AND id = ?2",
                params![system, body],
                |r| Ok((r.get::<_, Option<u32>>(0)?, r.get::<_, Option<String>>(1)?)),
            )
            .optional()?
            .and_then(|(seed, params)| Some((seed?, params?))))
    }

