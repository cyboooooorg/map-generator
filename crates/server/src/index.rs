//! The index: a SQLite database the server owns (`MAPGEN_DB`), beside the
//! tree of systems. See `docs/analysis/15-storage.md`, step 1.
//!
//! It holds what the server asks often, so that it no longer opens every
//! `system.json` to answer:
//!
//! - **systems and bodies**, as the library lists them, with what a body
//!   needs to be generated again (its seed and parameters), the generator
//!   version it was made with and when it was last opened;
//! - the **names** the user gave;
//! - the **jobs**, so that a restart does not lose them.
//!
//! The files stay where they are (the tree is the blob store: bodies are
//! written by [`crate::staging`], served as files). The index is rebuilt
//! from the tree when the database is missing or empty, and reconciled
//! with it on every start ([`Index::reconcile`]), so the files need no
//! migration step. The database itself has a layout version
//! (`PRAGMA user_version`): a file of another layout, older or newer, is
//! renamed `<file>.layout-<version>-<ms>` (with its `-wal` and `-shm`) and
//! a new database is made, with a warning. What only the index holds
//! (pins, last opened dates, displayed sizes, job history) is not rebuilt
//! from the tree. Names are written to `names.json` too, so that the
//! tree stays self-sufficient for now.
//!
//! One connection behind a mutex: the server's writes are few and short,
//! and always run on a blocking thread.
//!
//! The journal is WAL when the file system allows it (readers do not block
//! the writer, commits are cheaper), checked at every open: the mode must
//! answer `wal` and a write must round-trip. The file may sit on a bind
//! mount of the Docker VM (virtiofs), where WAL's shared memory is not a
//! given; if the check fails, the index logs a warning and uses SQLite's
//! default rollback journal. In WAL mode the database is the three files
//! `mapgen.sqlite`, `-wal` and `-shm`: copy it with the server stopped,
//! or with `sqlite3 mapgen.sqlite ".backup copy.sqlite"`.
use crate::api::{BodySummary, JobStatus, SystemSummary};
use crate::systems::{self, GivenNames};
use mapgen::request::WorldRequest;
use rusqlite::{Connection, OptionalExtension, Transaction, params};
use std::collections::{BTreeMap, HashMap, HashSet};
use std::path::Path;
use std::sync::Mutex;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

/// The generator a body is made with: the crate version (bumped with a
/// release), plus the build id when the build knows it: `0.1.0+<git sha>`
/// (see `build.rs`: `GIT_SHA` of the environment, else `git rev-parse`).
/// A build with neither is the bare crate version (and then no body is
/// announced as older for its build alone, see [`versions_differ`]) ...
pub const GENERATOR_VERSION: &str = match option_env!("MAPGEN_BUILD_ID") {
    Some(id) => id,
    None => env!("CARGO_PKG_VERSION"),
};
/// ... and the revision of what it writes (`world.json`'s `format_version`,
/// bumped with every change of the generated data). A body regenerated by
/// a newer revision is drawn by the current generator, not the one it
/// had.
pub const GENERATOR_FORMAT: u32 = mapgen::export::raw_data::FORMAT_VERSION;

/// The `generator_format` of a body evicted whose generator was never
/// known: it differs from every real revision, so the user is told that
/// the regenerated world may look different, and the body counts as
/// evicted (see [`Index::evicted_generator`]).
pub const UNKNOWN_FORMAT: i64 = 0;

/// Version of the database layout (`PRAGMA user_version`). A file of
/// another layout is set aside and a new one made (no migration): what
/// only the index held (pins, last opened dates, displayed sizes, the job
/// history) starts over, the rest is read again from the tree.
///
/// - 2: systems can be pinned in the main menu;
/// - 3: the displayed size of each body, the size a job generates.
const SCHEMA_VERSION: i64 = 3;
/// Least time between two writes of a body's last opened date: a viewer
/// asks for dozens of tiles a second.
const TOUCH_EVERY: Duration = Duration::from_secs(60);
/// What a job that was queued or running when the server stopped says.
pub const INTERRUPTED: &str = "interrupted by a server restart";

/// A failure of the index.
#[derive(Debug)]
pub struct IndexError(pub String);

impl std::fmt::Display for IndexError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "index: {}", self.0)
    }
}

impl From<rusqlite::Error> for IndexError {
    fn from(e: rusqlite::Error) -> Self {
        Self(e.to_string())
    }
}

type Result<T> = std::result::Result<T, IndexError>;

