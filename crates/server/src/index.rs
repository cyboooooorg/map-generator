    fn temp_root(name: &str) -> PathBuf {
        let root = std::env::temp_dir().join(format!("mapgen-index-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        root
    }

    /// A tree with systems `ids`, each the same file; "c" is generated
    /// with a `world.json` of format 9.
    fn tree(root: &Path, ids: &[&str]) {
        for id in ids {
            let dir = root.join(id);
            std::fs::create_dir_all(dir.join("bodies/c/raw_data")).unwrap();
            std::fs::write(dir.join("system.json"), SYSTEM).unwrap();
            std::fs::write(
                dir.join("bodies/c/raw_data/world.json"),
                r#"{"format_version": 9}"#,
            )
            .unwrap();
        }
    }

    fn ids(index: &Index) -> Vec<String> {
        let mut ids: Vec<String> = index
            .list_systems()
            .unwrap()
            .into_iter()
            .map(|s| s.id)
            .collect();
        ids.sort();
        ids
    }

