//! Tier-2 regression tests (see CLAUDE.md, Tests): shared reference
//! systems generated once per run on a coarse grid, then statistics,
//! contracts and determinism asserted on them.
//!
//! Test-only crate: it may depend on every engine, which a domain crate
//! may not, even as a dev-dependency.

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::sync::OnceLock;

use science::units::{Dex, SolarMass};
use system::planet::{ClassRead, class_read};
use system::{
    ArchetypeId, Drawn, Generated, INPUTS_SCHEMA, Inputs, Request, SystemRequest, generate_with,
};
use timeline::{BodyState, CauseGraph, Code, PlanetState, Seed, Timeline, Trace, fnv1a64};

/// Definition: the seeds of the shared reference systems, those of
/// [`reference_requests`] in order.
pub const REFERENCE_SEEDS: &[u64] = &[1, 2, 3, 4, 5, 6, 7, 8];

fn inputs(seed: u64, host: Option<f64>, archetypes: &[(&'static str, u32)]) -> Inputs {
    Inputs {
        schema: INPUTS_SCHEMA,
        seed: Seed::new(seed),
        present: None,
        request: Request::System(SystemRequest {
            host_mass: host.map(SolarMass),
            metallicity: Some(Dex(0.0)),
            archetypes: archetypes
                .iter()
                .map(|&(name, count)| (ArchetypeId(Code::of(name)), count))
                .collect::<BTreeMap<_, _>>(),
        }),
    }
}

/// The reference system requests: three free seeds, one per forced host
/// mass (0.3, 1 and 2 M☉), an `earth-like` and two `hot-neptune`.
#[must_use]
pub fn reference_requests() -> Vec<Inputs> {
    vec![
        inputs(1, None, &[]),
        inputs(2, None, &[]),
        inputs(3, None, &[]),
        inputs(4, Some(0.3), &[]),
        inputs(5, Some(1.0), &[]),
        inputs(6, Some(2.0), &[]),
        inputs(7, None, &[("earth-like", 1)]),
        inputs(8, None, &[("hot-neptune", 2)]),
    ]
}

/// One call of the draw's classifier: the circular trial it classified
/// (its seed, and the bits of its mass and semi-major axis, which tell
/// the tries of a slot apart: they share the slot's seed) and what the
/// planet model read of it.
#[derive(Clone, Copy, Debug)]
pub struct LoggedRead {
    pub seed: Seed,
    pub mass_bits: u64,
    pub axis_bits: u64,
    pub read: ClassRead,
}

/// A reference system, generated by `system::generate_with`.
#[derive(Debug)]
pub struct Reference {
    pub inputs: Inputs,
    pub drawn: Drawn,
    /// The draw's trace, then the model's nodes, in the draw's order: the
    /// ids `drawn` holds. The states of `timelines` hold ids of their own
    /// keyframe's graph instead.
    pub trace: Trace,
    /// The star's timeline, then one per placement of `drawn`, in order.
    pub timelines: Vec<Timeline>,
    /// Every classification the draw made, in order, rejected tries
    /// included.
    pub reads: Vec<LoggedRead>,
}

impl Reference {
    /// Per placement of `drawn`, in order: its present state and the cause
    /// graph of that state's keyframe.
    ///
    /// # Panics
    ///
    /// When a planet timeline's keyframe does not hold a planet.
    pub fn planets(&self) -> impl Iterator<Item = (&PlanetState, &CauseGraph)> {
        self.timelines[1..].iter().map(|timeline| {
            let keyframe = &timeline.keyframes[0];
            match keyframe.state() {
                BodyState::Planet(state) => (state, keyframe.causes()),
                _ => panic!("{}: not a planet keyframe", timeline.body),
            }
        })
    }
}

/// The reference systems, generated once per process by
/// `system::generate_with` with the planet model's classifier (every read
/// logged). Nextest runs each test in its own process: a test that calls
/// this pays the whole draw and model.
///
/// # Panics
///
/// When a reference request fails to generate.
pub fn references() -> &'static [Reference] {
    static REFERENCES: OnceLock<Vec<Reference>> = OnceLock::new();
    REFERENCES.get_or_init(|| {
        reference_requests()
            .into_iter()
            .map(|inputs| {
                let reads = RefCell::new(Vec::new());
                let Generated {
                    drawn,
                    trace,
                    timelines,
                } = generate_with(&inputs, |trial, trace| {
                    let read = class_read(trial, trace)?;
                    reads.borrow_mut().push(LoggedRead {
                        seed: trial.seed,
                        mass_bits: trial.mass.value().0.to_bits(),
                        axis_bits: trial.orbit.semi_major_axis.value().0.to_bits(),
                        read,
                    });
                    Ok(read.outcome)
                })
                .unwrap();
                Reference {
                    inputs,
                    drawn,
                    trace,
                    timelines,
                    reads: reads.into_inner(),
                }
            })
            .collect()
    })
}

/// The systems of [`reference_requests`], read from the one draw of
/// [`references`].
#[must_use]
pub fn reference_systems() -> Vec<&'static Drawn> {
    references().iter().map(|r| &r.drawn).collect()
}

fn real(value: f64) -> String {
    format!("{value:.8e}")
}

/// A canonical text of every value of a drawn system, hashed: its
/// designation, family, star and age, then per planet its mass, orbit,
/// spin and fluxes, each real written with 9 significant digits.
#[must_use]
pub fn digest(drawn: &Drawn) -> u64 {
    let star = &drawn.star;
    let mut text = format!(
        "{} {} {} {} {} {} {} {} {}",
        drawn.designation,
        drawn.family.code(),
        real(star.mass.value().0),
        real(star.radius.value().0),
        real(star.luminosity.value().0),
        real(star.effective_temperature.value().0),
        real(star.metallicity.value().0),
        real(drawn.age.value().0),
        drawn.placements.len(),
    );
    for placement in &drawn.placements {
        let orbit = &placement.trial.orbit;
        let source = placement.trial.sources.primary();
        text += &format!(
            "\n{} {} {} {} {} {} {} {} {} {}",
            placement.designation,
            real(placement.trial.mass.value().0),
            real(orbit.semi_major_axis.value().0),
            real(orbit.eccentricity.value().get()),
            real(orbit.period.value().0),
            real(orbit.perihelion_longitude.value().0),
            real(placement.spin.rotation_period.value().0),
            real(placement.spin.obliquity.value().0),
            real(source.flux.value().0),
            real(source.xuv.flux.value().0),
        );
    }
    fnv1a64(text.as_bytes())
}
