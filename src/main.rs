/// Procedural planet map generator.
///
/// Every omitted option comes from the planet preset or is chosen randomly;
/// the chosen values are printed so any world can be regenerated by passing
/// them back explicitly.
#[derive(Parser)]
#[command(version, about)]
struct Args {
    /// Planet preset: a built-in name (terran, volcanic, frozen, caustic,
    /// barren) or a path to a .toml preset file [default: random built-in]
    #[arg(long)]
    planet: Option<String>,

    /// List the built-in planet presets and exit
    #[arg(long)]
    list_planets: bool,

    /// Waterline shift in [-1, 1]; positive means more ocean [default: random in -0.30..0.50]
    #[arg(long, allow_negative_numbers = true, value_parser = parse_in_range(-1.0, 1.0))]
    sea_level: Option<f32>,

    /// Share of mountain chains that become volcanic, in [0, 1] [default: random]
    #[arg(long, value_parser = parse_in_range(0.0, 1.0))]
    volcanic: Option<f32>,

    /// Equatorial circumference in km [default: random in 20000..80000]
    #[arg(long, value_parser = parse_in_range(1.0, f32::MAX))]
    circumference: Option<f32>,

    /// Axial tilt in degrees, in [0, 90] [default: random in 5..40]
    #[arg(long, value_parser = parse_in_range(0.0, 90.0))]
    axial_tilt: Option<f32>,

    /// Hydraulic erosion strength in [0, 5]; 0 disables erosion [default: 1]
    #[arg(long, value_parser = parse_in_range(0.0, 5.0))]
    erosion: Option<f32>,

    /// Noise seed [default: random]
    #[arg(long)]
    seed: Option<u32>,

    /// Map width in pixels
    #[arg(long, default_value_t = 1920, value_parser = clap::value_parser!(u32).range(2..=16384))]
    width: u32,

    /// Map height in pixels
    #[arg(long, default_value_t = 1080, value_parser = clap::value_parser!(u32).range(2..=16384))]
    height: u32,

    /// Directory that receives the generated worlds
    #[arg(long, default_value = "worlds")]
    out_dir: PathBuf,

    /// Skip the raw_data/ export (world.json and the layer PNGs)
    #[arg(long)]
    no_raw_data: bool,

    /// Skip the diagnostic noise maps
    #[arg(long)]
    no_noise_maps: bool,
}

/// Builds a clap value parser that accepts an `f32` within `[min, max]`.
fn parse_in_range(min: f32, max: f32) -> impl Fn(&str) -> Result<f32, String> + Clone {
    move |s| {
        let v: f32 = s.parse().map_err(|e| format!("{e}"))?;
        if (min..=max).contains(&v) {
            Ok(v)
        } else {
            Err(format!("must be between {min} and {max}"))
        }
    }
}

fn main() -> ExitCode {
    match run(Args::parse()) {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run(args: Args) -> Result<(), Box<dyn Error>> {
    let mut rng = rand::rng();

    if args.list_planets {
        for preset in Preset::built_in() {
            println!("{:10} {}", preset.name, preset.description);
        }
        return Ok(());
    }

    let planet_spec = match args.planet {
        Some(spec) => spec,
        None => {
            let names = built_in_names();
            names[rng.random_range(0..names.len())].to_string()
        }
    };
    let planet = Preset::load(&planet_spec)?;

    // Command-line value, else the preset default, else the generator default.
    let mut resolve = |arg: Option<f32>, preset: Option<ParamDefault>, fallback: ParamDefault| {
        arg.unwrap_or_else(|| preset.unwrap_or(fallback).pick(&mut rng))
    };
    let d = planet.defaults.clone();
    let sea_level = resolve(
        args.sea_level,
        d.sea_level,
        ParamDefault::Range([-0.30, 0.50]),
    );
    let volcanic_intensity = resolve(args.volcanic, d.volcanic, ParamDefault::Range([0.0, 1.0]));
    // Sub-Earth to ~2× Earth (Earth ≈ 40 075 km).
    let circumference_km = resolve(
        args.circumference,
        d.circumference,
        ParamDefault::Range([20_000.0, 80_000.0]),
    );
    let axial_tilt_deg = resolve(
        args.axial_tilt,
        d.axial_tilt,
        ParamDefault::Range([5.0, 40.0]),
    );
    let erosion = resolve(args.erosion, d.erosion, ParamDefault::Fixed(1.0));
    let seed = args.seed.unwrap_or_else(|| rng.random());
    let planet_name = planet.name.clone();

    let params = WorldParams {
        width: args.width,
        height: args.height,
        seed,
        planet,
        sea_level,
        volcanic_intensity,
        circumference_km,
        axial_tilt_deg,
        erosion,
    };
    println!(
        "Parameters → planet={planet_name} seed={seed} sea_level={sea_level:.2} \
         volcanic={volcanic_intensity:.2} circumference={circumference_km:.0} km \
         tilt={axial_tilt_deg:.1}° gravity≈{:.2}g",
        params.gravity_modifier()
    );

    let generated = generate(&params);
    let world = &generated.world;

    let dir = args.out_dir.join(format!("{planet_name}-{seed}"));
    let dir_str = |sub: &str| dir.join(sub).to_string_lossy().into_owned();
    std::fs::create_dir_all(&dir)?;

    if !args.no_raw_data {
        std::fs::create_dir_all(dir.join("raw_data"))?;
    }
    if !args.no_noise_maps {
        std::fs::create_dir_all(dir.join("noise_maps"))?;
    }

    // Exports are independent and dominated by PNG encoding: run them in parallel.
    type Export<'a> = Box<dyn Fn() -> Result<(), String> + Send + Sync + 'a>;
    let mut exports: Vec<Export> = vec![
        Box::new(|| export_png(world, &dir_str("world.png")).map_err(|e| e.to_string())),
        Box::new(|| export_svg(world, &dir_str("world.svg")).map_err(|e| e.to_string())),
        Box::new(|| export_legend_png(world, &dir_str("legend.png")).map_err(|e| e.to_string())),
    ];
    if !args.no_raw_data {
        exports.push(Box::new(|| {
            export_raw_data(world, &dir.join("raw_data")).map_err(|e| e.to_string())
        }));
    }
    if !args.no_noise_maps {
        exports.push(Box::new(|| {
            export_noise_maps(
                &generated.debug,
                world.width,
                world.height,
                &dir_str("noise_maps"),
            )
            .map_err(|e| e.to_string())
        }));
    }
    exports.par_iter().try_for_each(|export| export())?;

    println!("World generated → {}/", dir.display());
    // Exact values (the summary above is rounded) so the world can be regenerated.
    println!(
        "Reproduce with: --planet {planet_spec} --seed {seed} --sea-level {sea_level} \
         --volcanic {volcanic_intensity} --circumference {circumference_km} \
         --axial-tilt {axial_tilt_deg} --erosion {erosion}"
    );
    Ok(())
}
